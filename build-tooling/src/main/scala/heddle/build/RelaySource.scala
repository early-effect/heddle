package heddle.build

import java.nio.charset.StandardCharsets.UTF_8
import java.security.MessageDigest
import java.util.Base64

import zio.*

private[build] final case class RelaySource(text: String, hash: String, literals: List[String]):
  def scalaSource: String =
    val parts = literals.mkString(",\n    ")
    s"""package heddle.mcp.apps.host
       |
       |import heddle.mcp.apps.ScriptHash
       |
       |/** The relay's linked script (`heddle-mcp-apps-relay`) and its CSP hash, generated by the build. Do not edit. */
       |private[host] object RelayScript:
       |  val hash: ScriptHash = ScriptHash("$hash")
       |
       |  val text: String = List(
       |    $parts
       |  ).mkString
       |""".stripMargin

private[build] object RelaySource:
  // HTML end tags are case insensitive. Preserve the JavaScript string's spelling and value.
  def escaped(linked: String): String =
    "(?i)</script".r.replaceAllIn(linked, found => "<\\\\/" + found.matched.drop(2))

  def generate(linked: String): IO[RelayBrowserError, RelaySource] =
    val script = escaped(linked)
    ZIO
      .attempt(MessageDigest.getInstance("SHA-256").digest(script.getBytes(UTF_8)))
      .mapError(_ => RelayBrowserError.HashUnavailable)
      .map: digest =>
        val hash = "sha256-" + Base64.getEncoder.encodeToString(digest)
        // Existing 8192-character chunks stay below the JVM constant limit even with six-byte Unicode escapes.
        val parts = script.grouped(8192).map(literal).toList
        RelaySource(script, hash, parts)

  private def literal(value: String): String =
    val escaped = value.flatMap:
      case '"'                     => "\\\""
      case '\\'                    => "\\\\"
      case '\n'                    => "\\n"
      case '\r'                    => "\\r"
      case '\t'                    => "\\t"
      case c if c < ' ' || c > '~' => f"\\u${c.toInt}%04x"
      case c                       => c.toString
    "\"" + escaped + "\""
end RelaySource
